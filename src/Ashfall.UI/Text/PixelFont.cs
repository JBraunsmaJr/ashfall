namespace Ashfall.UI.Text;

/// <summary>
/// A 5×7 pixel font, upper case, digits and common punctuation; lower case prints as upper case.
/// Glyphs are drawn as runs of solid pixels, so the UI needs no font texture until the art pass.
/// </summary>
public static class PixelFont
{
    public const int GlyphWidth = 5;
    public const int GlyphHeight = 7;

    /// <summary>Horizontal advance per character, in font pixels (glyph plus one pixel of spacing).</summary>
    public const int Advance = GlyphWidth + 1;

    private static readonly Dictionary<char, byte[]> Glyphs = Build();

    /// <summary>Row bitmasks (bit 4 is the leftmost pixel) for <paramref name="c"/>, or a box for unknown characters.</summary>
    public static ReadOnlySpan<byte> Rows(char c) =>
        Glyphs.TryGetValue(char.ToUpperInvariant(c), out var rows) ? rows : Glyphs['□'];

    /// <summary>Width of <paramref name="text"/> in pixels at <paramref name="scale"/>.</summary>
    public static float Measure(string text, float scale) =>
        string.IsNullOrEmpty(text) ? 0 : ((text.Length * Advance) - 1) * scale;

    private static Dictionary<char, byte[]> Build()
    {
        var glyphs = new Dictionary<char, byte[]>();
        void Add(char c, params string[] rows)
        {
            var bits = new byte[GlyphHeight];
            for (var y = 0; y < GlyphHeight; y++)
            {
                for (var x = 0; x < GlyphWidth; x++)
                {
                    if (rows[y][x] == '#')
                    {
                        bits[y] |= (byte)(1 << (GlyphWidth - 1 - x));
                    }
                }
            }

            glyphs[c] = bits;
        }

        Add('A', ".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#");
        Add('B', "####.", "#...#", "#...#", "####.", "#...#", "#...#", "####.");
        Add('C', ".###.", "#...#", "#....", "#....", "#....", "#...#", ".###.");
        Add('D', "####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####.");
        Add('E', "#####", "#....", "#....", "####.", "#....", "#....", "#####");
        Add('F', "#####", "#....", "#....", "####.", "#....", "#....", "#....");
        Add('G', ".###.", "#...#", "#....", "#.###", "#...#", "#...#", ".####");
        Add('H', "#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#");
        Add('I', ".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###.");
        Add('J', "..###", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##..");
        Add('K', "#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#");
        Add('L', "#....", "#....", "#....", "#....", "#....", "#....", "#####");
        Add('M', "#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#");
        Add('N', "#...#", "#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#");
        Add('O', ".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.");
        Add('P', "####.", "#...#", "#...#", "####.", "#....", "#....", "#....");
        Add('Q', ".###.", "#...#", "#...#", "#...#", "#.#.#", "#..#.", ".##.#");
        Add('R', "####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#");
        Add('S', ".####", "#....", "#....", ".###.", "....#", "....#", "####.");
        Add('T', "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#..");
        Add('U', "#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.");
        Add('V', "#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#..");
        Add('W', "#...#", "#...#", "#...#", "#.#.#", "#.#.#", "#.#.#", ".#.#.");
        Add('X', "#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#");
        Add('Y', "#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#..");
        Add('Z', "#####", "....#", "...#.", "..#..", ".#...", "#....", "#####");
        Add('0', ".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###.");
        Add('1', "..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###.");
        Add('2', ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####");
        Add('3', "#####", "...#.", "..#..", "...#.", "....#", "#...#", ".###.");
        Add('4', "...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#.");
        Add('5', "#####", "#....", "####.", "....#", "....#", "#...#", ".###.");
        Add('6', "..##.", ".#...", "#....", "####.", "#...#", "#...#", ".###.");
        Add('7', "#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#...");
        Add('8', ".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###.");
        Add('9', ".###.", "#...#", "#...#", ".####", "....#", "...#.", ".##..");
        Add(' ', ".....", ".....", ".....", ".....", ".....", ".....", ".....");
        Add('.', ".....", ".....", ".....", ".....", ".....", ".##..", ".##..");
        Add(',', ".....", ".....", ".....", ".....", ".##..", "..#..", ".#...");
        Add(':', ".....", ".##..", ".##..", ".....", ".##..", ".##..", ".....");
        Add(';', ".....", "..#..", "..#..", ".....", "..#..", "..#..", ".#...");
        Add('-', ".....", ".....", ".....", "#####", ".....", ".....", ".....");
        Add('+', ".....", "..#..", "..#..", "#####", "..#..", "..#..", ".....");
        Add('/', ".....", "....#", "...#.", "..#..", ".#...", "#....", ".....");
        Add('%', "##...", "##..#", "...#.", "..#..", ".#...", "#..##", "...##");
        Add('(', "...#.", "..#..", ".#...", ".#...", ".#...", "..#..", "...#.");
        Add(')', ".#...", "..#..", "...#.", "...#.", "...#.", "..#..", ".#...");
        Add('[', ".###.", ".#...", ".#...", ".#...", ".#...", ".#...", ".###.");
        Add(']', ".###.", "...#.", "...#.", "...#.", "...#.", "...#.", ".###.");
        Add('!', "..#..", "..#..", "..#..", "..#..", "..#..", ".....", "..#..");
        Add('?', ".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#..");
        Add('\'', "..#..", "..#..", ".#...", ".....", ".....", ".....", ".....");
        Add('<', "...#.", "..#..", ".#...", "#....", ".#...", "..#..", "...#.");
        Add('>', ".#...", "..#..", "...#.", "....#", "...#.", "..#..", ".#...");
        Add('=', ".....", ".....", "#####", ".....", "#####", ".....", ".....");
        Add('_', ".....", ".....", ".....", ".....", ".....", ".....", "#####");
        Add('$', "..#..", ".####", "#.#..", ".###.", "..#.#", "####.", "..#..");
        Add('#', ".#.#.", ".#.#.", "#####", ".#.#.", "#####", ".#.#.", ".#.#.");
        Add('×', ".....", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "....."); // ×
        Add('□', "#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"); // unknown
        return glyphs;
    }
}
